const { chromium } = require(process.env.TEMP + '/viejob-browser-tools/node_modules/playwright');
const assert = require('node:assert/strict');

(async function () {
    const browser = await chromium.launch({ executablePath: 'C:/Program Files (x86)/Microsoft/Edge/Application/msedge.exe', headless: true });
    const page = await browser.newPage({ viewport: { width: 390, height: 844 } });
    const errors = [];
    page.on('pageerror', error => errors.push(error.message));
    await page.goto('http://127.0.0.1:8012/');
    await page.locator('#overlayer').waitFor({ state: 'hidden' });
    await page.locator('.site-menu-toggle').click();
    await page.locator('.site-mobile-menu a').filter({ hasText: /^Việc làm$/ }).click();
    await page.waitForURL('**/viec-lam');
    await page.setViewportSize({ width: 1440, height: 900 });
    await page.goto('http://127.0.0.1:8012/dang-nhap');
    await page.getByRole('button', { name: 'Xem thử giao diện đã đăng nhập' }).click();
    await page.waitForURL('**/ung-vien/ho-so');
    await page.locator('#overlayer').waitFor({ state: 'hidden' });
    await page.locator('.candidate-avatar').hover();
    assert(await page.locator('.candidate-account .dropdown-menu').isVisible());
    await page.locator('.candidate-account a').filter({ hasText: 'Quản lý CV' }).click();
    await page.waitForURL('**/ung-vien/cv');
    await page.locator('#resume-pdf').setInputFiles({ name: 'kiem-tra.pdf', mimeType: 'application/pdf', buffer: Buffer.from('%PDF-1.4\n1 0 obj\n<< /Type /Catalog >>\nendobj\n%%EOF') });
    await page.locator('#resume-dropzone button').click();
    await page.waitForLoadState('networkidle');
    assert(await page.getByText('kiem-tra.pdf', { exact: false }).first().isVisible());
    await page.getByRole('link', { name: 'Xác nhận kỹ năng', exact: true }).click();
    await page.getByRole('button', { name: 'Nạp kỹ năng mẫu' }).click();
    await page.waitForLoadState('networkidle');
    await page.locator('#new-skill').fill('Docker');
    await page.locator('#add-skill').click();
    assert((await page.locator('#skills-editor').inputValue()).includes('Docker'));
    await page.getByRole('button', { name: 'Xác nhận dữ liệu demo' }).click();
    await page.goto('http://127.0.0.1:8012/ung-vien/goi-y-ai');
    assert(await page.locator('progress').count() > 0);
    await page.goto('http://127.0.0.1:8012/viec-lam/1');
    await page.locator('[data-target="#apply-modal"]').click();
    await page.locator('#application-confirmation').check();
    await page.getByRole('button', { name: 'Xác nhận ứng tuyển' }).click();
    await page.waitForURL('**/ung-vien/ung-tuyen');
    await page.getByRole('button', { name: 'Rút hồ sơ', exact: true }).click();
    await page.locator('#confirmation-modal').waitFor({ state: 'visible' });
    await page.locator('#confirmation-submit').click();
    await page.waitForLoadState('networkidle');
    assert(await page.getByRole('link', { name: 'Ứng tuyển lại', exact: true }).isVisible());
    await page.goto('http://127.0.0.1:8012/ung-vien/cai-dat');
    await page.locator('form[action$="/demo/xoa-du-lieu"] button').click();
    await page.locator('#confirmation-submit').click();
    await page.waitForURL('http://127.0.0.1:8012/');
    assert.deepEqual(errors, []);
    console.log('PASS: mobile menu, avatar hover, PDF upload, skill editor, recommendations, apply, withdraw confirmation, cleanup.');
    await browser.close();
})().catch(error => {
    console.error(error);
    process.exit(1);
});
